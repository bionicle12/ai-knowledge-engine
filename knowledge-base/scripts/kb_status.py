#!/usr/bin/env python3
"""kb_status — the session hand-off file STATUS.md for AI Knowledge Engine.

Collects pending work from the other scripts and writes ``<base>/STATUS.md``
(``status.file`` in kb.config.yml): one header line, then only the non-zero
items, each ending with the command that resolves it — or ``- all clear``.
kb_reindex.py calls it at the end of every run (all modes, including the git
hook); the agent reads the file at session start and runs this script on
``!status``.

Every input is optional; a missing or broken one drops its line, never the
file:
  review queues, merge queue,          kb_ingest.collect_status(root)
  extraction backlog,
  files stuck in raw/**/unsorted/
  reflection due                       kb_reflect.check(root)
  heal                                 summary comment on line 1 of
                                       review/needs-heal/HEAL_PLAN.md (kb_heal.py)
  index                                .repomix/manifest.json (kb_reindex.py)
  sessions awaiting meta-review        interactions/sessions/**/*.md without
                                       `meta_reviewed: true`
  lint                                 .kb-state/lint-summary.json (kb_lint.py)

Usage:
  python3 scripts/kb_status.py            # write STATUS.md and print it
  python3 scripts/kb_status.py --print    # print only, write nothing
  python3 scripts/kb_status.py --json     # machine-readable, write nothing

Exit status: 0; 1 when neither status.file nor STATUS.md may be written
(an existing file this script did not generate is never overwritten); 2 when
the root has no kb.config.yml.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import kb_common as kbc  # noqa: E402

HEADER = "# KB status — {when} (generated by kb_status.py, do not edit)"
DEFAULT_STATUS_FILE = "STATUS.md"
# kb_heal.py writes its plan into this review queue; the queue is reported
# on the heal line (→ !heal), never among the review queues (→ !review).
HEAL_QUEUE = "needs-heal"
# kb_import.py's conflicts and merge candidates: `!merge` resolves them and
# `!review` leaves them alone (04_REVIEW), so they get their own line.
MERGE_QUEUE = "needs-merge"
HEAL_PLAN_REL = f"review/{HEAL_QUEUE}/HEAL_PLAN.md"
HEAL_SUMMARY_RE = re.compile(r"<!--\s*heal-summary:(?P<fields>[^>]*?)-->")
LINT_SUMMARY = "lint-summary.json"
MANIFEST_REL = ".repomix/manifest.json"
SESSIONS_DIR = "interactions/sessions"


@dataclass
class StatusItem:
    key: str
    text: str
    command: str

    @property
    def line(self) -> str:
        return f"- {self.text} → {self.command}"


def _int(value: object) -> int:
    try:
        return int(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return 0


def _oldest(days: object) -> str:
    return f" (oldest {days}d)" if isinstance(days, int) else ""


def _ingest_items(root: Path) -> list[StatusItem]:
    import kb_ingest

    collect = getattr(kb_ingest, "collect_status", None)
    if collect is None:
        return []
    status = collect(root) or {}
    items: list[StatusItem] = []

    queues = status.get("review") or {}
    parts = [
        f"{queue} {_int(info.get('count'))}{_oldest(info.get('oldest_days'))}"
        for queue, info in sorted(queues.items())
        if queue not in (HEAL_QUEUE, MERGE_QUEUE)
        and isinstance(info, dict)
        and _int(info.get("count"))
    ]
    if parts:
        items.append(StatusItem("review", "review queues: " + ", ".join(parts), "!review"))
    merge = queues.get(MERGE_QUEUE)
    if isinstance(merge, dict) and _int(merge.get("count")):
        items.append(
            StatusItem(
                "merge",
                f"merge queue: {_int(merge.get('count'))}{_oldest(merge.get('oldest_days'))}",
                "!merge",
            )
        )

    pending = _int(status.get("extraction_pending"))
    if pending:
        items.append(
            StatusItem(
                "extraction",
                f"extraction pending in processed/: {pending}"
                f"{_oldest(status.get('extraction_pending_oldest_days'))}",
                "!review",
            )
        )

    unsorted = status.get("unsorted") or {}
    total = _int(unsorted.get("total"))
    if total:
        reasons = ", ".join(
            f"{reason} {_int(n)}"
            for reason, n in sorted((unsorted.get("by_reason") or {}).items())
            if _int(n)
        )
        items.append(
            StatusItem(
                "unsorted",
                f"stuck in raw/**/unsorted: {total}" + (f" ({reasons})" if reasons else ""),
                "python3 scripts/kb_ingest.py --status",
            )
        )
    return items


def _reflection_items(root: Path) -> list[StatusItem]:
    import kb_reflect

    check = getattr(kb_reflect, "check", None)
    if check is None:
        return []
    info = check(root) or {}
    if info.get("decision") != "THRESHOLD_MET":
        return []
    return [
        StatusItem(
            "reflection",
            f"reflection due (changes {info.get('changes')} ≥ {info.get('threshold')})",
            "!reflect",
        )
    ]


def _heal_items(root: Path) -> list[StatusItem]:
    plan = root / HEAL_PLAN_REL
    match = None
    if plan.is_file():
        with plan.open(encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(5))
        match = HEAL_SUMMARY_RE.search(head)
    if not match:
        # No machine-readable plan (none yet, or one from kb_heal.py before
        # 0.16): whatever waits in the queue still belongs to !heal.
        queue = plan.parent
        waiting = (
            sum(1 for p in queue.iterdir() if p.is_file() and not p.name.startswith("."))
            if queue.is_dir()
            else 0
        )
        if not waiting:
            return []
        text = f"heal: {waiting} file(s) waiting in review/{HEAL_QUEUE}/"
        return [StatusItem("heal", text, "!heal")]
    fields = dict(re.findall(r"(\w+)=(\S+)", match.group("fields")))
    counts = [(bucket, _int(fields.get(bucket))) for bucket in ("auto", "assisted", "human")]
    total = sum(n for _, n in counts)
    if not total:
        return []
    parts = ", ".join(f"{bucket} {n}" for bucket, n in counts if n)
    return [StatusItem("heal", f"heal: {total} open ({parts})", "!heal")]


def _legacy_index_items(manifest: dict) -> list[StatusItem]:
    """The monolithic output.xml of a base without an ``index:`` section."""
    entry = manifest.get("legacy")
    entry = entry if isinstance(entry, dict) else {}
    if manifest.get("error"):
        problems = ["not built"]
    else:
        problems = []
        if entry.get("state") == "FAILED":
            problems.append("FAILED")
        elif entry.get("state") == "STALE":
            problems.append("not rebuilt (repomix unavailable)")
        if entry.get("over_ceiling"):
            problems.append("OVER ceiling")
    if not problems:
        return []
    name = Path(str(entry.get("output") or "output.xml")).name
    text = f"index: legacy {name} " + ", ".join(problems)
    return [StatusItem("index", text, "see .repomix/PACKS_STATUS.md")]


def _index_items(root: Path) -> list[StatusItem]:
    path = root / MANIFEST_REL
    if not path.is_file():
        return []
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(manifest, dict):
        return []
    if manifest.get("mode") == "legacy":
        return _legacy_index_items(manifest)
    packs = manifest.get("packs")
    if not isinstance(packs, dict):
        return []
    entries = [e for e in packs.values() if isinstance(e, dict)]
    over = sum(1 for e in entries if e.get("over_ceiling"))
    failed = sum(1 for e in entries if e.get("state") == "FAILED")
    stale = sum(1 for e in entries if e.get("state") == "STALE")
    # Members repomix dropped from a built pack (security check, ignore file).
    left_out = sum(len(e["left_out"]) for e in entries if isinstance(e.get("left_out"), list))
    if manifest.get("error"):
        # The whole build stopped (invalid repomix.config.json, empty plan).
        return [StatusItem("index", "index: not built", "see .repomix/PACKS_STATUS.md")]
    problems = []
    if over or failed or stale:
        problems.append(f"{over} pack{'' if over == 1 else 's'} OVER ceiling, {failed} FAILED")
        if stale:
            problems.append(f"{stale} not rebuilt (repomix unavailable)")
    if left_out:
        problems.append(f"{left_out} file{'' if left_out == 1 else 's'} left out by repomix")
    if not problems:
        return []
    return [StatusItem("index", "index: " + ", ".join(problems), "see .repomix/PACKS_STATUS.md")]


def _session_items(root: Path) -> list[StatusItem]:
    sessions = root / SESSIONS_DIR
    if not sessions.is_dir():
        return []
    waiting = 0
    for path in sessions.rglob("*.md"):
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "meta_reviewed" in text:
            meta, _ = kbc.parse_frontmatter(text)
            if meta.get("meta_reviewed") is True:
                continue
        waiting += 1
    if not waiting:
        return []
    return [StatusItem("sessions", f"sessions awaiting meta-review: {waiting}", "!meta-review")]


def _lint_items(root: Path) -> list[StatusItem]:
    # Read-only: no kbc.state_dir() here, it would create the folder.
    path = root / kbc.STATE_DIR / LINT_SUMMARY
    if not path.is_file():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        return []
    errors, warnings = _int(data.get("errors")), _int(data.get("warnings"))
    if not (errors or warnings):
        return []
    return [
        StatusItem(
            "lint", f"lint: {errors} errors, {warnings} warnings", "python3 scripts/kb_lint.py"
        )
    ]


COLLECTORS: tuple[Callable[[Path], list[StatusItem]], ...] = (
    _ingest_items,
    _reflection_items,
    _heal_items,
    _index_items,
    _session_items,
    _lint_items,
)


def collect_items(root: Path) -> list[StatusItem]:
    """Every non-zero status item, in STATUS.md order."""
    items: list[StatusItem] = []
    for collect in COLLECTORS:
        try:
            items.extend(collect(root))
        except Exception as exc:  # noqa: BLE001 — one broken input must not hide the rest
            print(f"⚠️  [status] {collect.__name__.strip('_')} skipped: {exc}", file=sys.stderr)
    return items


def render(items: list[StatusItem], when: str | None = None) -> str:
    """STATUS.md text: the header, then one line per item (at most 10 lines)."""
    lines = [HEADER.format(when=when or kbc.now_iso()), ""]
    lines += [item.line for item in items] or ["- all clear"]
    return "\n".join(lines) + "\n"


def _is_ours(path: Path) -> bool:
    """True when overwriting ``path`` loses nothing: it does not exist, is
    empty, or starts with the header this script writes."""
    if not path.exists():
        return True
    if not path.is_file():
        return False
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            first = fh.readline()
    except OSError:
        return False
    return not first or (
        first.startswith(HEADER.split("{when}")[0]) and "generated by kb_status.py" in first
    )


def status_path(root: Path, cfg: "kbc.KbConfig") -> Path | None:
    """Where STATUS.md goes: ``status.file`` under the base root, else the
    default; ``None`` when neither may be written.

    A path outside the base, or a file this script did not generate
    (AGENTS.md, kb.config.yml, a knowledge page…), is never overwritten.
    """
    names = [cfg.status_file or DEFAULT_STATUS_FILE]
    if names[0] != DEFAULT_STATUS_FILE:
        names.append(DEFAULT_STATUS_FILE)
    for name in names:
        target = kbc.resolve_under(root, name)
        if target is None:
            problem = "points outside the base"
        elif not _is_ours(target):
            problem = "is an existing file not generated by kb_status.py"
        else:
            if name != names[0]:
                print(f"⚠️  [status] writing {name} instead", file=sys.stderr)
            return target
        print(f"⚠️  [status] status.file {name!r} {problem}; not overwriting it", file=sys.stderr)
    print("⚠️  [status] STATUS.md not written", file=sys.stderr)
    return None


def write_status(
    root: Path, *, cfg: "kbc.KbConfig | None" = None, items: list[StatusItem] | None = None
) -> tuple[Path | None, list[StatusItem]]:
    """Write STATUS.md atomically; returns its path (``None`` when no
    allowed target exists, see :func:`status_path`) and the items."""
    cfg = cfg or kbc.load_config(root)
    if items is None:
        items = collect_items(root)
    path = status_path(root, cfg)
    if path is not None:
        kbc.atomic_write_text(path, render(items))
    return path, items


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="AI Knowledge Engine — write the STATUS.md session hand-off"
    )
    parser.add_argument("--root", type=Path, default=None)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--print", action="store_true", help="print STATUS.md, write nothing")
    mode.add_argument("--json", action="store_true", help="print the items as JSON, write nothing")
    args = parser.parse_args(argv)

    root = Path(args.root or kbc.find_kb_root()).resolve()
    if not kbc.kb_config_path(root).is_file():
        print(
            f"❌ [status] {root} is not a knowledge base (no "
            f"{kbc.DEFAULT_CONFIG_FILENAME}); run it from the base root or pass --root",
            file=sys.stderr,
        )
        return 2
    cfg = kbc.load_config(root)
    items = collect_items(root)
    if args.json:
        payload = {
            "generated_at": kbc.now_iso(),
            "file": cfg.status_file,
            "enabled": cfg.status_enabled,
            "all_clear": not items,
            "items": [asdict(item) for item in items],
        }
        print(json.dumps(payload, ensure_ascii=False, indent=2))
        return 0
    if args.print:
        print(render(items), end="")
        return 0
    if not cfg.status_enabled:
        print(
            "status.enabled is false in kb.config.yml — nothing written "
            "(--print shows the status)"
        )
        return 0
    path, _ = write_status(root, cfg=cfg, items=items)
    if path is None:
        print(render(items), end="")
        return 1
    print(path.read_text(encoding="utf-8"), end="")
    print(f"→ {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
