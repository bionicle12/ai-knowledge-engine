def test_missing_or_broken_inputs_drop_only_their_line(base: Path, monkeypatch, capsys):
    _busy_base(base, monkeypatch)

    def broken(root):
        raise RuntimeError("metadata unreadable")

    monkeypatch.setattr(kb_ingest, "collect_status", broken, raising=False)
    monkeypatch.delattr(kb_reflect, "check", raising=False)  # an older kb_reflect
    _write(base, ".repomix/manifest.json", "{not json")
    _write(base, ".kb-state/lint-summary.json", "[1, 2]")
    _write(base, "review/needs-heal/.gitkeep", "")  # hidden: not a plan
    os.remove(base / HEAL_PLAN)

    keys = [item.key for item in kb_status.collect_items(base)]

    assert keys == ["sessions"]
    err = capsys.readouterr().err
    assert "ingest_items skipped: metadata unreadable" in err
    assert "index_items skipped" in err


def test_cli_print_and_json_write_nothing(base: Path, monkeypatch, capsys):
    _busy_base(base, monkeypatch)

    assert kb_status.main(["--root", str(base), "--print"]) == 0
    out = capsys.readouterr().out
    assert "- reflection due (changes 31 ≥ 25) → !reflect" in out
    assert not (base / "STATUS.md").exists()

    assert kb_status.main(["--root", str(base), "--json"]) == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["all_clear"] is False
    assert payload["file"] == "STATUS.md"
    assert {
        "key": "lint",
        "text": "lint: 0 errors, 4 warnings",
        "command": "python3 scripts/kb_lint.py",
    } in payload["items"]
    assert not (base / "STATUS.md").exists()


def test_cli_writes_the_configured_file(base: Path, capsys):
    assert kb_status.main(["--root", str(base)]) == 0
    written = (base / "STATUS.md").read_text("utf-8")
    assert written.endswith("- all clear\n")
