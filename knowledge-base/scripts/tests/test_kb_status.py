def test_heal_line_reads_the_plan_in_its_review_queue(base: Path, monkeypatch):
    # kb_heal.py writes review/needs-heal/HEAL_PLAN.md; kb_ingest reports that
    # folder as a review queue, but it is resolved by !heal, not !review.
    monkeypatch.setattr(
        kb_ingest,
        "collect_status",
        lambda r: {"review": {"needs-heal": {"count": 1, "oldest_days": 2}}},
        raising=False,
    )
    plan = _write(
        base,
        HEAL_PLAN,
        "<!-- heal-summary: version=0.16.0 plan_id=1a2b3c4d stage=2 auto=0 assisted=3 human=1 -->\n",
    )
    assert [i.line for i in kb_status.collect_items(base)] == [
        "- heal: 4 open (assisted 3, human 1) → !heal"
    ]

    # A plan from kb_heal.py before 0.16 has no summary: still !heal.
    plan.write_text("# Heal plan\n", encoding="utf-8")
    assert [i.line for i in kb_status.collect_items(base)] == [
        "- heal: 1 file(s) waiting in review/needs-heal/ → !heal"
    ]

    # Nothing open, nothing reported (and never as a review queue).
    plan.write_text(
        "<!-- heal-summary: version=0.16.0 plan_id=0 stage=5 auto=0 assisted=0 human=0 -->\n",
        encoding="utf-8",
    )
    assert kb_status.collect_items(base) == []


def test_merge_queue_goes_to_merge_not_review(base: Path, monkeypatch):
    # kb_import.py stages conflicts in review/needs-merge/; `!review` leaves
    # that folder to `!merge` (04_REVIEW), so STATUS.md must not send it there.
    monkeypatch.setattr(
        kb_ingest,
        "collect_status",
        lambda r: {
            "review": {
                "needs-ai-decision": {"count": 1, "oldest_days": None},
                "needs-merge": {"count": 2, "oldest_days": 3},
            }
        },
        raising=False,
    )
    assert [i.line for i in kb_status.collect_items(base)] == [
        "- review queues: needs-ai-decision 1 → !review",
        "- merge queue: 2 (oldest 3d) → !merge",
    ]


