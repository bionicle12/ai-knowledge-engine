def test_legacy_index_reports_the_monolith_not_old_packs(base: Path):
    manifest = {
        "mode": "legacy",
        "packs": {},
        "legacy": {"output": ".repomix/output.xml", "state": "rebuilt", "over_ceiling": False},
    }
    _write(base, ".repomix/manifest.json", json.dumps(manifest))
    assert kb_status.collect_items(base) == []

    manifest["legacy"].update(state="FAILED", over_ceiling=True)
    _write(base, ".repomix/manifest.json", json.dumps(manifest))
    [item] = kb_status.collect_items(base)
    assert item.line == (
        "- index: legacy output.xml FAILED, OVER ceiling → see .repomix/PACKS_STATUS.md"
    )

    manifest["legacy"].update(state="STALE", over_ceiling=False)
    _write(base, ".repomix/manifest.json", json.dumps(manifest))
    [item] = kb_status.collect_items(base)
    assert item.text == "index: legacy output.xml not rebuilt (repomix unavailable)"


def test_status_file_never_overwrites_a_file_it_did_not_generate(base: Path, capsys):
    agents = _write(base, "AGENTS.md", "# AGENTS instructions IMPORTANT\n")
    (base / "kb.config.yml").write_text(
        'knowledge_base:\n  name: t\nstatus:\n  file: "AGENTS.md"\n', encoding="utf-8"
    )

    assert kb_status.main(["--root", str(base)]) == 0

    assert agents.read_text("utf-8") == "# AGENTS instructions IMPORTANT\n"
    assert (base / "STATUS.md").read_text("utf-8").endswith("- all clear\n")
    assert "not generated by kb_status.py" in capsys.readouterr().err

    # Its own earlier output is overwritten; a foreign STATUS.md is not.
    assert kb_status.main(["--root", str(base)]) == 0
    status = _write(base, "STATUS.md", "my own notes\n")
    assert kb_status.main(["--root", str(base)]) == 1
    assert status.read_text("utf-8") == "my own notes\n"
    assert agents.read_text("utf-8") == "# AGENTS instructions IMPORTANT\n"
    assert "STATUS.md not written" in capsys.readouterr().err


